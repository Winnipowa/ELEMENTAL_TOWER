import fs from 'node:fs';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';

// Bootstrap from the source renderers without importing the generated index: a clean rebuild
// must still work if meta/art/sprites/ was removed. Only the transport function is replaced.
const transportImport=['import','{spriteImage}','from',"'./mobile-assets.js';"].join(' ');
const rendererSource=fs.readFileSync('meta/art.js','utf8');
if(!rendererSource.includes(transportImport))throw new Error('Unknown art transport import');
const buildTransport='function spriteImage(sheet){return `<image data-source-href="./art/sources/${sheet.file}"/>`;}';
const {SHEETS,GUARDIAN_ART,guardianVisual,elementBadge,referenceStudy,abilityArt,codexArt}=await import('data:text/javascript;base64,'+Buffer.from(rendererSource.replace(transportImport,buildTransport)).toString('base64'));

// Lossless derivatives only. Logical rectangles are read from the actual renderers, not re-authored.
const ffmpeg=process.env.FFMPEG_PATH||'ffmpeg',padding=24;
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const decode=file=>execFileSync(ffmpeg,['-v','error','-i',file,'-f','rawvideo','-pix_fmt','rgba','pipe:1'],{maxBuffer:16000000});
const provenance=JSON.parse(fs.readFileSync('meta/art/provenance.json','utf8'));
const markup=Object.keys(GUARDIAN_ART).map(portraitKey=>{const g={portraitKey};return guardianVisual(g)+elementBadge(g)+referenceStudy(g)+abilityArt(g);}).join('')+codexArt();
const rectangles=new Map();
for(const match of markup.matchAll(/<svg viewBox="([^"]+)"[\s\S]*?<image\b([^>]+)>/g)){
 const source=match[2].match(/data-source-href="\.\/art\/sources\/([^"]+)"/)?.[1];
 if(!source)throw new Error('Missing source provenance in renderer');
 const rect=match[1].split(' ').map(Number);rectangles.set(source+':'+rect.join(','),{source,rect});
}
fs.mkdirSync('meta/art/sprites',{recursive:true});
const records=[],rawSources=new Map(),index={};
for(const [key,{source,rect}]of rectangles){
 const original=provenance.records.find(r=>r.file===source),sheet=Object.values(SHEETS).find(s=>s.file===source);
 if(!original||!sheet)throw new Error('Unknown sheet '+source);
 const input='meta/art/sources/'+source;
 if(hash(fs.readFileSync(input))!==original.sha256)throw new Error('Original changed '+source);
 const [x,y,w,h]=rect,cx=Math.max(0,x-padding),cy=Math.max(0,y-padding),cw=Math.min(sheet.width,x+w+padding)-cx,ch=Math.min(sheet.height,y+h+padding)-cy;
 const file=source.replace('.png','')+'_'+rect.join('_')+'.png',output='meta/art/sprites/'+file;
 execFileSync(ffmpeg,['-v','error','-i',input,'-vf',`crop=${cw}:${ch}:${cx}:${cy}:exact=1`,'-c:v','png','-compression_level','9','-pred','mixed','-pix_fmt','rgba','-y',output]);
 if(!rawSources.has(source))rawSources.set(source,decode(input));
 const expected=Buffer.alloc(cw*ch*4),raw=rawSources.get(source);
 for(let row=0;row<ch;row++)raw.copy(expected,row*cw*4,((cy+row)*sheet.width+cx)*4,((cy+row)*sheet.width+cx+cw)*4);
 const actual=decode(output);if(!actual.equals(expected))throw new Error('Crop RGBA differs '+key);
 const bytes=fs.readFileSync(output);
 const entry={file,x:cx,y:cy,width:cw,height:ch};index[key]=entry;
 records.push({key,source,sourceSha256:original.sha256,mappingRect:rect,cropRect:[cx,cy,cw,ch],...entry,bytes:bytes.length,rgbaBytes:actual.length,sha256:hash(bytes),rgbaSha256:hash(expected),rgbaIdentical:true});
 console.log(file+': '+bytes.length+' bytes');
}
fs.writeFileSync('meta/art/sprites/index.js','// Generated by npm run assets:sprites. Original logical coordinates remain authoritative.\nexport const SPRITES='+JSON.stringify(index,null,2)+';\n');
fs.writeFileSync('meta/art/sprites/provenance.json',JSON.stringify({schemaVersion:1,padding,recipe:'PNG crop exact, rgba, compression_level=9 pred=mixed; original viewBox/clip retained',encoder:execFileSync(ffmpeg,['-version'],{encoding:'utf8'}).split(/\r?\n/)[0],records},null,2)+'\n');
